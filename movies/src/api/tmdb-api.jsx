// underrated (like hidden gems on tmdb)
// idea is high rating with low total ratings, implying its good but lowkey
// highest rating first, rating above 8, less than 2000 reviews
export const getUnderratedMovies = () => {
  return fetch(
    `https://api.themoviedb.org/3/discover/movie?api_key=${import.meta.env.VITE_TMDB_KEY}&sort_by=vote_average.desc&vote_average.gte=8&vote_count.lte=2000&page=1`
  )
    .then((res) => res.json())
    .then((json) => json.results);
};



